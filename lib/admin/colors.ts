import "server-only";
import { describeColor, gradientCss } from "../color";
import { db } from "../db";
import type { Color } from "../generated/prisma/client";
import { deleteFiles, storeFile } from "./files";

const kebab = (s: string) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/** colors.json and colors.css, in the same format the asset pipeline has always written. */
export function colorFiles(brand: { name: string; slug: string; updatedAt: Date }, colors: Color[]) {
  const seen = new Set<string>();
  const cssVar = (name: string) => {
    let v = `--${brand.slug}-${kebab(name)}`;
    for (let n = 2; seen.has(v); n++) v = `--${brand.slug}-${kebab(name)}-${n}`;
    seen.add(v);
    return v;
  };
  const list = colors.map((c) => {
    if (c.kind === "GRADIENT") {
      const g = c.gradient as { angle: number; stops: { hex: string; at: number }[] };
      return { name: c.name, role: c.role, type: "gradient" as const, css: gradientCss(g.angle, g.stops), angle: g.angle, stops: g.stops.map((s) => ({ at: s.at, ...describeColor(s.hex) })), cssVar: cssVar(c.name) };
    }
    return { name: c.name, role: c.role, ...describeColor(c.hex ?? "#000000"), cmyk: c.cmyk ?? undefined, pantone: c.pantone ?? undefined, cssVar: cssVar(c.name) };
  });
  const palettes = [{ name: "Main palette", colors: list }];
  const json = JSON.stringify({ brand: brand.name, slug: brand.slug, updatedAt: brand.updatedAt.toISOString().slice(0, 10), palettes }, null, 2) + "\n";
  const css =
    `/* ${brand.name} brand colors. Generated by the brand admin. */\n:root {\n` +
    `  /* Main palette */\n` +
    list.map((c) => `  ${c.cssVar}: ${"css" in c ? c.css : c.hex}; /* ${c.role} */`).join("\n") +
    "\n}\n";
  return { json, css };
}

/** Rewrites the brand's colors.css / colors.json (or removes them when it has no colors). */
export async function regenerateColorFiles(brandId: string) {
  const b = await db.brand.findUniqueOrThrow({ where: { id: brandId }, include: { colors: { orderBy: { sortOrder: "asc" } } } });
  const old = [b.colorsCssFileId, b.colorsJsonFileId];
  let css = null;
  let json = null;
  if (b.colors.length) {
    const files = colorFiles(b, b.colors);
    css = await storeFile({ brandId, kind: "colors", name: "colors.css", bytes: Buffer.from(files.css), mime: "text/css" });
    json = await storeFile({ brandId, kind: "colors", name: "colors.json", bytes: Buffer.from(files.json), mime: "application/json" });
  }
  // Raw SQL: regenerating files isn't an edit of its own (the color change already counted).
  await db.$executeRaw`UPDATE "Brand" SET "colorsCssFileId" = ${css?.id ?? null}, "colorsJsonFileId" = ${json?.id ?? null} WHERE "id" = ${brandId}`;
  await deleteFiles(old);
}
